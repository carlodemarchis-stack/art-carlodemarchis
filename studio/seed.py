def k(name):
    """A file inside sources/keynote-2025 by its prefix."""
    hits = glob.glob(os.path.join(KEY, glob.escape(name) + "*"))
    if not hits:
        print("  ! keynote source not found:", name)
    return hits[0] if hits else os.path.join(KEY, name)


def g(pattern, n=None, skip=()):
    hits = sorted(p for p in glob.glob(pattern) if not any(s in p for s in skip))
    if not hits:
        print("  ! no files for", pattern)
    return hits[:n] if n else hits


